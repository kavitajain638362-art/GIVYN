"""Shared workspace storage for deployments with stateless Flask instances."""

from contextlib import contextmanager
from threading import Lock

from .storage import SCHEMA, Store

POSTGRES_SCHEMA = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
POSTGRES_SCHEMA = POSTGRES_SCHEMA.replace("INTEGER NOT NULL REFERENCES analyses", "BIGINT NOT NULL REFERENCES analyses")
POSTGRES_SCHEMA = POSTGRES_SCHEMA.replace("INTEGER PRIMARY KEY REFERENCES analyses", "BIGINT PRIMARY KEY REFERENCES analyses")
POSTGRES_SCHEMA = POSTGRES_SCHEMA.replace(
    "DEFAULT CURRENT_TIMESTAMP", "DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"
)


class WorkspaceStorageUnavailable(RuntimeError):
    pass


class PostgresStore(Store):
    def __init__(self, dsn):
        self.dsn = dsn
        self._ready = False
        self._schema_lock = Lock()

    @contextmanager
    def connection(self):
        from psycopg import Error, connect
        from psycopg.rows import dict_row

        try:
            with connect(self.dsn, connect_timeout=5, row_factory=dict_row) as connection:
                if not self._ready:
                    with self._schema_lock:
                        if not self._ready:
                            # Serialize initial schema creation across cold instances.
                            with connection.transaction():
                                connection.execute("SELECT pg_advisory_xact_lock(756224208)")
                                connection.execute(POSTGRES_SCHEMA, prepare=False)
                            self._ready = True
                yield WorkspaceConnection(connection)
        except Error:
            raise WorkspaceStorageUnavailable from None


class WorkspaceConnection:
    """Adapt the placeholder syntax for the fixed, parameterized Store queries."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params):
        return self.connection.execute(sql.replace("?", "%s"), params, prepare=False)
